CREATE INDEX ON vector_store USING HNSW (embedding vector_cosine_ops);	

DROP TABLE IF EXISTS TRANSMISSION_STATUS_HIST;
DROP TABLE IF EXISTS TRANSMISSION_STATUS;
DROP TABLE IF EXISTS TRANSMISSION_ERROR;

-- Tables for Transmissions
CREATE TABLE IF NOT EXISTS TRANSMISSION_STATUS(
	TRANSMISSION_STATUS_ID SERIAL NOT NULL UNIQUE,
	RECEIPT_ID VARCHAR(32) NOT NULL UNIQUE,
	STATUS VARCHAR(100) NOT NULL,
	FORM_TYPE VARCHAR(100) NOT NULL,
	SERVER VARCHAR(100) NOT NULL,
	INSERTED_DT TIMESTAMP NOT NULL,
	UPDATE_DT TIMESTAMP NOT NULL,
	PRIMARY KEY (TRANSMISSION_STATUS_ID)
);

CREATE TABLE IF NOT EXISTS TRANSMISSION_STATUS_HIST(
	TRANSMISSION_STATUS_HIST_ID SERIAL NOT NULL UNIQUE,
	TRANSMISSION_STATUS_ID SERIAL NOT NULL,
	RECEIPT_ID VARCHAR(32) NOT NULL,
	STATUS VARCHAR(100),
	INSERTED_DT TIMESTAMP NOT NULL,
	PRIMARY KEY (TRANSMISSION_STATUS_HIST_ID),
	FOREIGN KEY (TRANSMISSION_STATUS_ID) REFERENCES TRANSMISSION_STATUS (TRANSMISSION_STATUS_ID)
);

CREATE TABLE IF NOT EXISTS TRANSMISSION_ERROR(
	TRANSMISSION_ERROR_ID SERIAL NOT NULL UNIQUE,
	RECEIPT_ID VARCHAR(32) NOT NULL,
	ERROR_CD VARCHAR(100) NOT NULL,
	ERROR_MSG VARCHAR(4000) NOT NULL,
	ERROR_LEVEL VARCHAR(100) NOT NULL,
	LINE_NUM VARCHAR(100),
  XPATH_MAPPING VARCHAR(1000),
	ADDITIONAL_INFO VARCHAR(2000),
	PRIMARY KEY (TRANSMISSION_ERROR_ID)
);
