--PostgresSQL create script

-- DROP DATABASE IF EXISTS "AI_POC";

CREATE DATABASE "AI_POC"
    WITH
    OWNER = postgres
    ENCODING = 'UTF8'
    LC_COLLATE = 'English_United States.1252'
    LC_CTYPE = 'English_United States.1252'
    LOCALE_PROVIDER = 'libc'
    TABLESPACE = pg_default
    CONNECTION LIMIT = -1
    IS_TEMPLATE = False;

DROP ROLE IF EXISTS ai_poc_usr;
CREATE ROLE ai_poc_usr WITH LOGIN PASSWORD 'ai_poc_pwd';
GRANT ALL PRIVILEGES ON DATABASE "AI_POC" TO ai_poc_usr;
GRANT USAGE ON SCHEMA public to ai_poc_usr;
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA public TO ai_poc_usr;
GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA public TO ai_poc_usr;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO ai_poc_usr;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO ai_poc_usr;

-- database must be configred as vestor store
CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS hstore;
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

CREATE TABLE IF NOT EXISTS vector_store (
	id uuid DEFAULT uuid_generate_v4() PRIMARY KEY,
	content text,
	metadata json,
	embedding vector(768)
);
